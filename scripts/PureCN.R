    if(length(atrx_idx) > 0){
        atrx_vcf <- vcf_raw[atrx_idx,]
        # Filter for PASS
        pass_idx <- which(rowRanges(atrx_vcf)$FILTER == "PASS")
        atrx_vcf <- atrx_vcf[pass_idx, ]
        # Also filter for min AF and depth
        if(nrow(atrx_vcf) > 0){
            keep <- as.numeric(geno(atrx_vcf)$AF) >= opt$min_af &
