# Retrieve ATRX gene mutations (those on chrX)
annotates_to_gene <- function(ann_list, gene_name) {
  sapply(ann_list, function(anns) {
    any(sapply(anns, function(ann) {
      fields <- strsplit(ann, "\\|")[[1]]
      length(fields) >= 4 && fields[4] == gene_name
    }))
  })
}

