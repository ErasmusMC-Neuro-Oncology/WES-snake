#########################################################################/**
# @RdocFunction EstimateErrorAbsoluteProfile
#
# @title "Calculate Error (not normalized) for specific absolute copy number profile"
#
# @synopsis
#
# \description{
#     @get "title".
# }
#
# \arguments{
#     \item{q}{Vector of absolute copy number level, as generated in the function EstimateErrorTissue}
#     \item{segmentdata}{segmentdata$lengths correspond to the absolute copy number level}
# }

EstimateErrorAbsoluteProfile <- function(segmentdata,q){
   return(sum(segmentdata$lengths*abs(q-round(q)) ) )
}

EstimateErrorAbsoluteProfile_SD <- function(segmentdata,q){
   return(sum(segmentdata$lengths*abs(q-round(q))) -sum(segmentdata$lengths*segmentdata$q_sd_segs *sqrt(2/pi)))
}

#########################################################################/**
# @RdocFunction EstimateErrorTissue
#
# @title "Calculate Error (not normalized) for specific absolute copy number profile. This function is called repeatedly with different Purity and Ploidy to find the lowest value"
#
# @synopsis
#
# \description{
#     @get "title".
# }
#
# \arguments{
#     \item{Purity}{Purity of tumor sample, not necessarily the optimal purity}
#     \item{segmentdata}{dataframe as generated by DataFrameToSegmentWeights}
#     \item{Ploidy}{Ploidy of tumor sample, not necessarily the optimal Ploidy}
# }


EstimateErrorTissue <- function(segmentdata,Purity,Ploidy){
#  print(paste("Estimate",Purity,Ploidy))
  a1 = (Purity*Ploidy+ 2*(1-Purity))/Purity
  a2 = -2*(1-Purity)/Purity
  q = a1*segmentdata$values + a2

  return(EstimateErrorAbsoluteProfile(segmentdata,q))
}

EstimateErrorTissue_SD <- function(segmentdata,Purity,Ploidy){
  a1 = (Purity*Ploidy+ 2*(1-Purity))/Purity
  a2 = -2*(1-Purity)/Purity
  q = a1*segmentdata$values + a2
  segmentdata$q_sd_segs = a1*segmentdata$sd_segs 

  return(EstimateErrorAbsoluteProfile_SD(segmentdata,q))
}



Heterogeneity <- function(segmentdata,k){
  return(sum(segmentdata$lengths*abs(segmentdata$values*k - round(segmentdata$values*k))) /sum(segmentdata$lengths))
}

#########################################################################/**
# @RdocFunction EstimateHeterogeneity
#
# @title "Fit heterogeneity. Tries multiple purities and ploidies and returns an error Matrix, called r - sorry for the confusing variable name!"
#
# @synopsis
#
# \description{
#     @get "title".
# }
#
# \arguments{
#     \item{Purity}{Vector of potential Purities for tumor sample}
#     \item{df}{dataframe as generated by DataFrameToSegmentWeights}
#     \item{Ploidy}{Vector of potential Ploidies of tumor sample}
# }


EstimateHeterogeneity <- function(df, Ploidy=seq(1.5,5,0.01), Purity = seq(0.05,1.005,0.01)){
  r=matrix(rep(0,length(Ploidy)*length(Purity)),ncol=length(Ploidy),nrow=length(Purity))

#  print(paste(Purity,Ploidy))
  ind1=1
  ind2=1
  for(ind1 in 1:length(Purity)){
    for(ind2 in 1:length(Ploidy)){
      r[ind1,ind2]=EstimateErrorTissue(df,Purity[ind1],Ploidy[ind2])
    }
  }

# normalize Error matrix outside of the loop as it is faster 

  r = r/sum(df$values,df$lengths);
  return(r)
}

#########################################################################/**
# @RdocFunction ComputeMinimum
#
# @title ""
#
# @synopsis
#
# \description{
#     @get "title".
# }
#
# \arguments{
#     \item{Purity}{Vector of potential Purities for tumor sample}
#     \item{r}{error matrix as generated by EstimateHeterogeneity}
#     \item{Ploidy}{Vector of potential Ploidies of tumor sample}
# }


ComputeMinimum <- function(Ploidy=seq(1.5,5,0.01), Purity = seq(0.05,1.005,0.01),r){
  MinIndr= which(r==min(r))

  MinIndr = MinIndr

  MinPloidy = Ploidy[  floor((MinIndr[1]-1) / nrow(r))+1  ]
  MinPurity = Purity[((MinIndr[1]-1) %% nrow(r))+1]

  mr = min(r)

  MinHeterogeneity = mr[1] 
  return(list(MinHeterogeneity,MinPurity,MinPloidy,r))   
}


