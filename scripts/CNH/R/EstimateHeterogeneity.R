# @RdocFunction DataFrameToSegmentWeights
#
# @title "Converts data frame on bin level to data frame on segment level. Format is explained in detail below"
#
# @synopsis
#
# \description{
#     @get "title".
# }
#
# \arguments{
#     \item{df}{dataframe as generated by DataFrameToSegmentWeights}
# }



DataFrameToSegmentWeights <- function(df){
#converts dataframe from format:
#      	chr	start	end	segments
#	1	1	999	0.5
#	1	1000	1999	0.5
#	1	2000	2999	-0.3
#	1	3000	3999	NA
#	1	4000	4999	-0.3
#
#to:
#
#value	length
#0.5	2000
#-0.3	3000
# some effort needs to be done to handle missing data

  dfNoNA = df[!is.na(df$segments),]

  tmp = rle(as.vector(na.exclude(df$segments)))
  cSum = cumsum(tmp$lengths)

  if(length(cSum)>1){
    startCoordinates = c(dfNoNA$start[1],dfNoNA$start[cSum[1:(length(cSum)-1)]+1])
  }
  else{
    startCoordinates=c(dfNoNA$start[1])
  }
  endCoordinates = dfNoNA$end[cSum]
  chrom=dfNoNA$chrom[cSum]

  segmentdata = data.frame(startCoordinates=startCoordinates,endCoordinates=endCoordinates,chrom=chrom,values=tmp$values,lengths=endCoordinates-startCoordinates+1)
  weightedmean = (sum(segmentdata$values*segmentdata$lengths)/sum(segmentdata$lengths))

  if(weightedmean <0.5){
    segmentdata$values = 2^segmentdata$values
     weightedmean = (sum(segmentdata$values*segmentdata$lengths)/sum(segmentdata$lengths))
  }
  segmentdata$values =  segmentdata$values/weightedmean


  return(segmentdata)
}

